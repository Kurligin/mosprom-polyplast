def plural(n: int, forms: tuple[str, str, str]) -> str:
    """plural(5, ("день", "дня", "дней")) → «дней»."""
    n = abs(n)
    if n % 10 == 1 and n % 100 != 11:
        return forms[0]
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return forms[1]
    return forms[2]


def day_month(d: date) -> str:
    return f"{d.day} {MONTHS_GEN[d.month - 1]}"


def probation_when(end: date, today: date) -> str:
    """«25 января, через 5 дней» / «завтра, 25 января» / «сегодня»."""
    left = (end - today).days
    if left <= 0:
        return "сегодня"
    if left == 1:
        return f"завтра, {day_month(end)}"
    return f"{day_month(end)}, через {left} {plural(left, ('день', 'дня', 'дней'))}"
